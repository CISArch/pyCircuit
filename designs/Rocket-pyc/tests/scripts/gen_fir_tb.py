#!/usr/bin/env python3
"""gen_fir_tb.py — 为 fir2pyc 产物 TestHarness.v 里的 Rocket 核生成测试 tb。

fir2pyc 的核是新版配置（btb 前端反馈、dprv/data_raw 等 514 端口），
与 v16 golden 核端口集不同，不能直接套 tb_rocket_pgm.v；本脚本解析
`module Rocket (…)` 端口清单，按映射表生成 tb_rocket_fir2pyc.v：

  - imem：v16 同款自由跑取指模型（fpc/redirect/red_d，+imem 加载 1KiB）
  - dmem：两级移位队列（req_ready=1，resp 恰在 fire+2，load 预提取），
    复用 HellaCache s2 契约；store 写数据直接用 fire 拍的 req_bits_data/mask
  - 前端反馈（resp.btb/bht 字段）全 0：预测器学不到任何东西，
    架构正确性不受影响（仅顺序取指）
  - 判定：dmem store 事务流（fire 拍 addr/data），程序写 0x80=PASS

用法：python3 gen_fir_tb.py <TestHarness.v> <out tb.v>
"""
import re
import sys

# ---------- 输入端口 → 驱动表达式（未列出者默认 0） ----------
IN_MAP = {
    "clock": "clk", "reset": "reset", "pyc_clk": "clk", "pyc_rst": "reset",
    "iohartid": "1'b0",
    "ioreset_vector": "32'h00001000",
    # imem 模型
    "ioimem_resp_valid": "i_iresp_valid",
    "ioimem_resp_bits_pc": "i_iresp_pc",
    "ioimem_resp_bits_data": "i_iresp_data",
    "ioimem_resp_bits_mask": "2'b11",
    # dmem 模型
    "iodmem_req_ready": "1'b1",
    "iodmem_s2_paddr": "q2_addr[31:0]",
    "iodmem_resp_valid": "i_dresp_valid",
    "iodmem_resp_bits_addr": "q2_addr",
    "iodmem_resp_bits_tag": "i_dresp_tag",
    "iodmem_resp_bits_cmd": "q2_cmd",
    "iodmem_resp_bits_size": "q2_size",
    "iodmem_resp_bits_signed": "q2_signed",
    "iodmem_resp_bits_data": "i_dresp_data",
    "iodmem_resp_bits_data_word_bypass": "i_dresp_data",
    "iodmem_resp_bits_mask": "8'hFF",
    "iodmem_resp_bits_has_data": "i_dresp_has_data",
    "iodmem_ordered": "1'b1",
    "ioimem_clock_enabled": "1'b1",
    "iodmem_clock_enabled": "1'b1",
}
# ---------- 输出端口 → 观测 wire（未列出者空连） ----------
OUT_MAP = {
    "ioimem_might_request": "o_might_req",
    "ioimem_req_valid": "o_ireq_valid",
    "ioimem_req_bits_pc": "o_ireq_pc",
    "ioimem_req_bits_speculative": "o_ireq_spec",
    "ioimem_resp_ready": "o_iresp_ready",
    "ioimem_btb_update_valid": "o_btb",
    "ioimem_bht_update_valid": "o_bht",
    "ioimem_sfence_valid": "o_sfence_im",
    "iodmem_req_valid": "o_dreq_valid",
    "iodmem_req_bits_addr": "o_daddr",
    "iodmem_req_bits_tag": "o_dtag",
    "iodmem_req_bits_cmd": "o_dcmd",
    "iodmem_req_bits_size": "o_dsize",
    "iodmem_req_bits_signed": "o_dsigned",
    "iodmem_req_bits_data": "o_ddata",
    "iodmem_req_bits_mask": "o_dmask",
    "iodmem_s1_kill": "o_s1_kill",
    "iodmem_s1_data_data": "o_s1data",
    "ioptw_status_wfi": "o_wfi",
}
# 位宽（观测 wire 声明）
WIDTHS = {
    "o_ireq_pc": 34, "o_daddr": 34, "o_dtag": 6, "o_dcmd": 5, "o_dsize": 2,
    "o_ddata": 64, "o_dmask": 8, "o_s1data": 64,
    "i_iresp_pc": 34, "i_iresp_data": 32, "i_dresp_tag": 6, "i_dresp_data": 64,
}


def parse_ports(src):
    m = re.search(r"^module Rocket \((.*?)^\);", src, re.S | re.M)
    assert m, "module Rocket not found"
    ports = []
    for line in m.group(1).splitlines():
        mm = re.match(r"\s*(input|output)\s*(?:\[(\d+):(\d+)\])?\s*(\w+),?\s*$",
                      line.strip())
        if mm:
            d, hi, lo, name = mm.groups()
            w = 1 if hi is None else int(hi) - int(lo) + 1
            ports.append((d, w, name))
    return ports


def main(src_path, out_path):
    ports = parse_ports(open(src_path).read())
    inst, wires, assigns = [], [], []
    for d, w, name in ports:
        if d == "input":
            expr = IN_MAP.get(name, f"{w}'d0")
            inst.append(f"        .{name}({expr})")
            if name in IN_MAP and not IN_MAP[name].startswith(("1'b", "2'b", "8'h", "32'h")):
                if IN_MAP[name] in WIDTHS:  # 模型 wire，由 tb 主体声明
                    pass
        else:
            wname = OUT_MAP.get(name)
            if wname:
                inst.append(f"        .{name}({wname})")
                if wname not in [x.split()[1] for x in wires if x]:
                    wires.append(f"    wire [{WIDTHS.get(wname,1)-1}:0] {wname};" if WIDTHS.get(wname,1) > 1 else f"    wire {wname};")
            else:
                inst.append(f"        .{name}()")   # 空连
    decl = "\n".join(wires)
    inst_code = ",\n".join(inst)

    tb = f"""// AUTO-GENERATED by gen_fir_tb.py — DO NOT EDIT
// tb for fir2pyc Rocket (new-config core inside TestHarness.v).
// 判定口径同 tests/asm：store 到 0x80 写 0x55AA55AA → PASS。
`timescale 1ns/1ps
module tb_Rocket_fir;
    reg clk = 0;
    reg reset = 1;
    always #5 clk = ~clk;

{decl}

    // ---------- imem model（同 tb_rocket_pgm.v） ----------
    reg [31:0] imem [0:255];
    reg [33:0] fpc;
    reg        red_d = 0;
    wire       redirect_now = o_ireq_valid && !reset;
    wire       iresp_fire = !red_d && o_iresp_ready;
    wire       i_iresp_valid = !red_d;
    wire [33:0] i_iresp_pc  = fpc;
    wire [31:0] i_iresp_data = imem[fpc[11:2]];

    reg [1023:0] imem_file;
    integer cycles_arg, max_tick;
    initial begin
        if (!$value$plusargs("imem=%s", imem_file)) begin
            $display("ERROR: +imem=<hex> required"); $finish;
        end
        if (!$value$plusargs("cycles=%d", max_tick)) max_tick = 1500;
        for (integer k = 0; k < 256; k = k + 1) imem[k] = 32'h0000006f;
        $readmemh(imem_file, imem);
        fpc = 34'h000001000;
    end

    always @(posedge clk) begin
        if (reset)              fpc <= 34'h000001000;
        else if (redirect_now)  fpc <= o_ireq_pc;
        else if (iresp_fire)    fpc <= fpc + 4;
    end

    // ---------- dmem model：两级移位（HellaCache s2 契约，同 tb_rocket_pgm.v） ----------
    reg [63:0] dmem8 [0:255];
    reg        q1_v = 0, q2_v = 0;
    reg        q1_is_load = 0, q2_is_load = 0;
    reg        q1_signed = 0, q2_signed = 0;
    reg [4:0]  q1_cmd = 0, q2_cmd = 0;
    reg [33:0] q1_addr = 0, q2_addr = 0;
    reg [1:0]  q1_size = 0, q2_size = 0;
    reg [63:0] q1_data = 0, q2_data = 0;
    reg [7:0]  q1_mask = 0, q2_mask = 0;
    reg [5:0]  q1_tag = 0, q2_tag = 0;
    wire [5:0] i_dresp_tag = q2_tag;
    wire       i_dresp_has_data = q2_is_load;
    wire       i_dresp_valid = q2_v;

    wire [63:0] q_line = dmem8[q2_addr[11:3]];
    wire [31:0] q_word = q2_addr[2] ? q_line[63:32] : q_line[31:0];
    wire [15:0] q_half = q_line[16 * q2_addr[2:1] +: 16];
    wire [7:0]  q_byte = q_line[8  * q2_addr[2:0] +: 8];
    reg  [63:0] ldata;
    always @* begin
        case (q2_size)
            2'd3: ldata = q_line;
            2'd2: ldata = {{32'b0, q_word}};
            2'd1: ldata = q2_signed ? {{{{48{{q_half[15]}}}}, q_half}} : {{48'b0, q_half}};
            2'd0: ldata = q2_signed ? {{{{56{{q_byte[7]}}}}, q_byte}} : {{56'b0, q_byte}};
            default: ldata = 64'd0;
        endcase
    end
    wire [63:0] i_dresp_data = q2_is_load ? ldata : 64'd0;

    // store 写回（q2 拍沿 = fire+2）：读改写
    // 新版 Rocket：req.bits.data/mask 为 DontCare；真实 store 数据在
    // s1_data.data（req 后一拍有效）。q2 拍时 o_s1data 正好对应 q2 里的
    // req；mask 由 size/addr 生成（s1_data.mask 也是 DontCare）。
    reg [7:0] s1_mask;
    always @* begin
        case (q2_size)
            2'd3: s1_mask = 8'hFF;
            2'd2: s1_mask = q2_addr[2] ? 8'hF0 : 8'h0F;
            2'd1: s1_mask = 8'b00000011 << q2_addr[2:0];
            2'd0: s1_mask = 8'b00000001 << q2_addr[2:0];
            default: s1_mask = 8'h00;
        endcase
    end
    wire [63:0] w_shift = o_s1data << {{8*q2_addr[2:0]}};
    reg  [63:0] blk;
    always @(posedge clk) begin
        if (reset) begin
            q1_v <= 0; q2_v <= 0;
            for (integer k = 0; k < 256; k = k + 1) dmem8[k] <= 64'd0;
        end else begin
            if (q2_v && !q2_is_load) begin
                blk = dmem8[q2_addr[11:3]];
                if (s1_mask[0]) blk[7:0]   = w_shift[7:0];
                if (s1_mask[1]) blk[15:8]  = w_shift[15:8];
                if (s1_mask[2]) blk[23:16] = w_shift[23:16];
                if (s1_mask[3]) blk[31:24] = w_shift[31:24];
                if (s1_mask[4]) blk[39:32] = w_shift[39:32];
                if (s1_mask[5]) blk[47:40] = w_shift[47:40];
                if (s1_mask[6]) blk[55:48] = w_shift[55:48];
                if (s1_mask[7]) blk[63:56] = w_shift[63:56];
                dmem8[q2_addr[11:3]] <= blk;
            end
            q2_v <= q1_v; q2_is_load <= q1_is_load; q2_signed <= q1_signed;
            q2_cmd <= q1_cmd; q2_addr <= q1_addr; q2_size <= q1_size;
            q2_data <= q1_data; q2_mask <= q1_mask; q2_tag <= q1_tag;
            q1_v <= o_dreq_valid;
            q1_is_load <= (o_dcmd == 5'd0);
            q1_signed <= o_dsigned;
            q1_cmd <= o_dcmd; q1_addr <= o_daddr; q1_size <= o_dsize;
            q1_data <= o_ddata; q1_mask <= o_dmask; q1_tag <= o_dtag;
        end
    end

    // ---------- 判定与观测 ----------
    reg [33:0] last_st_addr = 0;
    reg [63:0] last_st_data = 0;
    integer    st_count = 0;
    wire store_fire = o_dreq_valid && (o_dcmd != 5'd0);

    integer tick;
    initial begin
        @(posedge clk); #1;
        for (tick = 0; tick < max_tick; tick = tick + 1) begin
            #1;
            reset = (tick < 3);
            red_d = reset ? 1'b0 : o_ireq_valid;
            @(posedge clk);
            #1;
            if (store_fire_prev) begin
                last_st_addr <= st_pend_addr; last_st_data <= o_s1data;
                st_count <= st_count + 1;
            end
            $display("PG %0d %0d %0d %0d %0d %0d %0d %0d %0h",
                tick, reset, o_ireq_valid, o_ireq_pc, o_dreq_valid,
                o_daddr, o_dcmd, o_s1data, o_wfi);
        end
        $display("VERDICT stores=%0d last_addr=%0d last_data=%0h",
                 st_count, last_st_addr, last_st_data);
        $finish;
    end
    // store fire 沿采样子（沿时刻 o_* 是沿后新值，改在 #1 窗口锁存）
    reg store_fire_prev = 0;
    reg [33:0] st_pend_addr = 0;
    reg [63:0] st_pend_data = 0;
    always @(posedge clk) begin
        store_fire_prev <= store_fire;
        st_pend_addr <= o_daddr;
        st_pend_data <= o_ddata;
    end

    // ---------- DUT ----------
    Rocket dut (
{inst_code}
    );
endmodule
"""
    # 修掉 tag 声明顺序问题（q2_tag 声明挪到使用前）
    tb = tb.replace("    wire [5:0] i_dresp_tag = q2_tag;\n    wire       i_dresp_has_data = q2_is_load;\n    wire       i_dresp_valid = q2_v;\n    wire [5:0]  q2_tag; // noqa — assigned below\n",
                    "    wire [5:0]  q2_tag;\n    wire [5:0] i_dresp_tag = q2_tag;\n    wire       i_dresp_has_data = q2_is_load;\n    wire       i_dresp_valid = q2_v;\n")
    open(out_path, "w").write(tb)
    print(f"wrote {out_path}: {len(ports)} ports")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
